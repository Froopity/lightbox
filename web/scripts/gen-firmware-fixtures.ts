// Writes firmware/test/test_protocol/fixtures_gen.h from shared/protocol-fixtures.json (PLAN.md §4), so the
// firmware parser runs the same golden cases as the web suite. `--check` fails if the header is stale.
import { readFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { resolve } from 'node:path'
import type { DeviceState } from '../src/protocol/device'
import type { Fixture } from '../src/protocol/fixtures'
import { MAX_COLORS, MAX_PARAMS } from '../src/styles/types'
import { writeOrCheck } from './gen-util'

const ROOT = resolve(fileURLToPath(import.meta.url), '../../..')
const FIXTURES_JSON = resolve(ROOT, 'shared/protocol-fixtures.json')
const HEADER = resolve(ROOT, 'firmware/test/test_protocol/fixtures_gen.h')

export const MAX_BEFORE = 4
/** Order of the expected-state slots; -1 means "not checked". */
const STATE_SLOTS = 4 + MAX_COLORS + MAX_PARAMS + 4

const cstr = (s: string): string => JSON.stringify(s) // ASCII only: JSON escapes are valid C escapes

function stateSlots(s: Partial<DeviceState> | undefined): (number | string)[] {
  const color = (c: string | undefined): number | string => (c === undefined ? -1 : `0x${c.slice(1).toUpperCase()}`)
  return [
    s?.style ?? -1,
    s?.rate ?? -1,
    s?.brightness ?? -1,
    s?.global ?? -1,
    ...Array.from({ length: MAX_COLORS }, (_, i) => color(s?.colors?.[i])),
    ...Array.from({ length: MAX_PARAMS }, (_, i) => s?.params?.[i] ?? -1),
    s?.lfo?.on ?? -1,
    s?.lfo?.target ?? -1,
    s?.lfo?.mHz ?? -1,
    s?.lfo?.depth ?? -1,
  ]
}

function row(f: Fixture): string {
  if ((f.expectReply === undefined) === (f.expectError === undefined)) {
    throw new Error(`fixture "${f.name}": needs exactly one of expectReply / expectError`)
  }
  const before = f.before ?? []
  if (before.length > MAX_BEFORE) throw new Error(`fixture "${f.name}": more than ${MAX_BEFORE} before lines`)
  if (!/^[\x20-\x7e]*$/.test(f.line + before.join(''))) throw new Error(`fixture "${f.name}": non-printable line`)
  const beforeList = Array.from({ length: MAX_BEFORE }, (_, i) => (before[i] === undefined ? 'nullptr' : cstr(before[i])))
  return (
    `    {${cstr(f.name)}, {${beforeList.join(', ')}}, ${cstr(f.line)}, ` +
    `${f.expectReply === undefined ? 'nullptr' : cstr(f.expectReply)}, ${f.expectError ?? 0}, ` +
    `{${stateSlots(f.expectState).join(', ')}}},`
  )
}

export function render(boot: DeviceState, fixtures: Fixture[]): string {
  return [
    '// GENERATED by web/scripts/gen-firmware-fixtures.ts from shared/protocol-fixtures.json. Do not edit.',
    '#pragma once',
    '#include <stdint.h>',
    '',
    `constexpr uint8_t MAX_BEFORE = ${MAX_BEFORE};`,
    `constexpr uint8_t STATE_SLOTS = ${STATE_SLOTS};  // style, rate, brightness, global, colours, params, LFO on/target/mHz/depth`,
    '',
    'struct Fixture {',
    '  const char* name;',
    '  const char* before[MAX_BEFORE];  // nullptr-padded; each must reply OK',
    '  const char* line;',
    '  const char* reply;  // expected success reply, or nullptr when an error is expected',
    '  uint8_t error;      // expected ERR code, 0 for success',
    '  int32_t state[STATE_SLOTS];  // expected state after the line; -1 = not checked',
    '};',
    '',
    `const int32_t BOOT_STATE[STATE_SLOTS] = {${stateSlots(boot).join(', ')}};`,
    '',
    'const Fixture FIXTURES[] = {',
    ...fixtures.map(row),
    '};',
    '',
  ].join('\n')
}

function main(): void {
  const { boot, fixtures } = JSON.parse(readFileSync(FIXTURES_JSON, 'utf8')) as { boot: DeviceState; fixtures: Fixture[] }
  writeOrCheck(HEADER, render(boot, fixtures), process.argv.includes('--check'))
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main()
