// Writes firmware/lib/core/styles_gen.h from shared/styles.json (PLAN.md §2.4).
// `--check` exits non-zero if the committed header is out of date.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { resolve } from 'node:path'

export interface ParamSpec {
  key: string
  label: string
  wireMin: number
  wireMax: number
  default: number
  scale: number
  unit?: string
}

export interface StyleSpec {
  id: number
  key: string
  name: string
  colors: number
  periodSlowMs: number
  periodFastMs: number
  bMin: number
  bMax: number
  defaultColors: string[]
  params: ParamSpec[]
}

export const MAX_COLORS = 2
export const MAX_PARAMS = 4

const ROOT = resolve(fileURLToPath(import.meta.url), '../../..')
export const STYLES_JSON = resolve(ROOT, 'shared/styles.json')
export const HEADER = resolve(ROOT, 'firmware/lib/core/styles_gen.h')

const hex = (c: string): string => `0x${c.replace('#', '').toUpperCase()}`

function styleRow(s: StyleSpec): string {
  const colors = Array.from({ length: MAX_COLORS }, (_, i) => hex(s.defaultColors[i] ?? '#000000'))
  const params = Array.from({ length: MAX_PARAMS }, (_, i) => {
    const p = s.params[i]
    return p ? `{${p.wireMin}, ${p.wireMax}, ${p.default}}` : '{0, 0, 0}'
  })
  return (
    `    {${s.id}, ${s.colors}, ${s.periodSlowMs}, ${s.periodFastMs}, ${s.bMin}, ${s.bMax}, ` +
    `${s.params.length}, {${colors.join(', ')}}, {${params.join(', ')}}},  // ${s.name}`
  )
}

export function render(styles: StyleSpec[]): string {
  styles.forEach((s, i) => {
    if (s.id !== i) throw new Error(`style ${s.key}: id ${s.id} must equal its index ${i}`)
    if (s.params.length > MAX_PARAMS) throw new Error(`style ${s.key}: more than ${MAX_PARAMS} params`)
    if (s.colors > MAX_COLORS) throw new Error(`style ${s.key}: more than ${MAX_COLORS} colours`)
  })
  const keys = styles.map((s) => `  STYLE_${s.key.toUpperCase()} = ${s.id},`)
  const lines = [
    '// GENERATED by web/scripts/gen-firmware-styles.ts from shared/styles.json. Do not edit.',
    '#pragma once',
    '#include <stdint.h>',
    '',
    'namespace core {',
    '',
    `constexpr uint8_t MAX_COLORS = ${MAX_COLORS};`,
    `constexpr uint8_t MAX_PARAMS = ${MAX_PARAMS};`,
    `constexpr uint8_t STYLE_COUNT = ${styles.length};`,
    '',
    'struct ParamDef {',
    '  uint16_t wireMin, wireMax, def;',
    '};',
    '',
    'struct StyleDef {',
    '  uint8_t id, colors;',
    '  uint32_t periodSlowMs, periodFastMs;',
    '  uint8_t bMin, bMax, paramCount;',
    '  uint32_t defaultColors[MAX_COLORS];',
    '  ParamDef params[MAX_PARAMS];',
    '};',
  ]
  if (styles.length > 0) {
    lines.push('', 'enum StyleId : uint8_t {', ...keys, '};', '', 'constexpr StyleDef STYLES[STYLE_COUNT] = {', ...styles.map(styleRow), '};')
  }
  lines.push('', '}  // namespace core', '')
  return lines.join('\n')
}

function main(): void {
  const { styles } = JSON.parse(readFileSync(STYLES_JSON, 'utf8')) as { styles: StyleSpec[] }
  const out = render(styles)
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(HEADER, 'utf8')
    } catch {
      // missing counts as stale
    }
    if (current !== out) {
      console.error('styles_gen.h is out of date: run `make gen`')
      process.exit(1)
    }
    console.log('styles_gen.h up to date')
  } else {
    writeFileSync(HEADER, out)
    console.log(`wrote ${HEADER}`)
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main()
